#!/usr/bin/env python3
"""Decode the supplied Cinepak movies without another lossy video conversion."""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def prepare(source: Path, output: Path, force=False):
    output.mkdir(parents=True, exist_ok=True)
    movies = {}
    for name in ("SO3DOP", "SO3DEDA", "SO3DEDB"):
        original = source / "PCSONIC/CDDATA" / (name + ".AVI")
        digest = hashlib.sha256(original.read_bytes()).hexdigest()
        target = output / name.lower()
        target.mkdir(exist_ok=True)
        manifest = target / "manifest.json"
        old = json.loads(manifest.read_text()) if manifest.exists() else {}
        complete = (old.get("sha256") == digest and
                    len(list(target.glob("[0-9]*.png"))) == old.get("frames") and
                    (target / "audio.wav").exists())
        if complete and not force:
            meta = old
        else:
            data = json.loads(subprocess.check_output([
                "ffprobe", "-v", "error", "-show_streams", "-of", "json", str(original)]))
            video = next(s for s in data["streams"] if s["codec_type"] == "video")
            fps = Fraction(video["r_frame_rate"])
            subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(original),
                            "-map", "0:v:0", "-fps_mode", "passthrough", "-pix_fmt", "rgb24",
                            "-compression_level", "3", str(target / "%06d.png")], check=True)
            subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(original),
                            "-map", "0:a:0", "-c:a", "copy", str(target / "audio.wav")], check=True)
            frames = int(video["nb_frames"])
            if len(list(target.glob("[0-9]*.png"))) != frames:
                raise RuntimeError(f"Incomplete movie decode: {name}")
            meta = dict(source=str(original.relative_to(source)), sha256=digest, frames=frames,
                        width=video["width"], height=video["height"],
                        fps_n=fps.numerator, fps_d=fps.denominator)
            manifest.write_text(json.dumps(meta, indent=2) + "\n")
        movies[name.lower()] = meta
        print(f"{name}: {meta['frames']} frames, {meta['width']}x{meta['height']}, original PCM audio")
    entries = []
    for name, meta in movies.items():
        values = ", ".join(f"{key}={meta[key]}" for key in ("frames", "width", "height", "fps_n", "fps_d"))
        entries.append(f"  {name} = {{{values}}},")
    (output / "index.lua").write_text("-- Generated by tools/prepare_movies.py\nreturn {\n" +
                                      "\n".join(entries) + "\n}\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "source")
    parser.add_argument("--output", type=Path, default=ROOT / "game/movies")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    prepare(args.source.resolve(), args.output.resolve(), args.force)
